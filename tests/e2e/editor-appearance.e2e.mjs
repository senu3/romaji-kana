import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { artifactPath, screenshotPath } from '../helpers/artifacts.mjs';

const server = await createServer({ cacheDir: artifactPath('cache/e2e'), server: { host: '127.0.0.1', port: 0, strictPort: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await context.addInitScript(() => {
    localStorage.setItem('romaji-kana-settings', JSON.stringify({ autoConvert: false }));
    localStorage.setItem('romaji-kana-document-session', JSON.stringify({ kind: 'new', content: '日本語とABC 123' }));
  });
  const page = await context.newPage();
  const errors = [], fontRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/\.(ttf|woff2?)(?:\?|$)/.test(request.url())) fontRequests.push(request.url()); });
  await page.route('**/api/tags', route => route.fulfill({ json: { models: [{ name: 'gemma3' }] } }));
  await page.goto(server.resolvedUrls.local[0]);
  const editor = page.locator('.cm-content');
  await editor.waitFor();
  const uiFont = await page.locator('.app-brand').evaluate(el => getComputedStyle(el).fontFamily);
  const trigger = page.getByRole('button', { name: 'エディターの表示設定', exact: true });
  const panel = page.getByRole('dialog', { name: 'エディターの表示', exact: true });
  await trigger.click();
  const font = panel.getByRole('combobox', { name: 'フォント名', exact: true });
  await font.pressSequentially('Times New Roman');
  assert.equal(await font.inputValue(), 'Times New Roman', 'A font name must allow typing spaces');
  const size = panel.getByRole('spinbutton', { name: '文字サイズ', exact: true });
  await size.fill(''); await size.pressSequentially('20');
  await font.focus();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.cm-scroller')).fontSize === '20px');
  assert.match(await page.locator('.cm-scroller').evaluate(el => getComputedStyle(el).fontFamily), /Times New Roman/);
  assert.equal(await page.locator('.app-brand').evaluate(el => getComputedStyle(el).fontFamily), uiFont);
  assert.equal(await editor.textContent(), '日本語とABC 123');
  await page.screenshot({ path: await screenshotPath('test-results/editor-appearance/desktop.png') });
  await page.reload();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.cm-scroller')).fontSize === '20px');
  await trigger.click();
  assert.equal(await font.inputValue(), 'Times New Roman');
  assert.equal(await size.inputValue(), '20');
  await page.keyboard.press('Escape');
  assert.equal(await panel.count(), 0);
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('combobox', { name: '表示テーマ' }).selectOption('dark');
  await trigger.click();
  const box = await panel.boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 390);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await panel.getByRole('button', { name: '標準に戻す', exact: true }).click();
  assert.equal(await font.inputValue(), '');
  assert.equal(await size.inputValue(), '16');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.cm-scroller')).fontSize === '16px');
  await page.screenshot({ path: await screenshotPath('test-results/editor-appearance/mobile-dark.png') });
  await editor.click();
  assert.equal(await panel.count(), 0);
  assert.deepEqual(errors, []);
  assert.deepEqual(fontRequests, [], 'No font file should be downloaded');
  await context.close();
  console.log('Editor appearance E2E passed: editable local font, live size, persistence, reset, keyboard, mobile, dark theme and no font downloads.');
} finally { await browser?.close(); await server.close(); }
