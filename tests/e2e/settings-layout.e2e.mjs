import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import { artifactPath, screenshotPath } from '../helpers/artifacts.mjs';

const server = await createServer({ cacheDir: artifactPath('cache/e2e-settings-layout'), server: { host: '127.0.0.1', port: 0, strictPort: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  let disconnected = false;
  await page.route('**/api/tags', route => disconnected ? route.abort('connectionrefused') : route.fulfill({ json: { models: [{ name: 'gemma3' }, { name: 'test-model' }] } }));
  await page.route('**/api/generate', route => route.fulfill({ json: { response: 'ok' } }));
  await page.goto(server.resolvedUrls.local[0]);
  await page.locator('.model-chip.connected').waitFor();
  assert.equal((await page.locator('.status-main').innerText()).trim(), '');
  await page.getByRole('button', { name: 'モデル設定を開く', exact: true }).click();
  const model = page.getByRole('dialog', { name: 'モデル', exact: true });
  await model.waitFor();
  assert.equal(await model.locator('.model-details').getAttribute('open'), null);
  await model.getByRole('combobox', { name: 'モデル', exact: true }).fill('test-model');
  await model.getByRole('option', { name: 'test-model', exact: true }).click();
  await page.locator('.model-chip.connected').filter({ hasText: 'test-model' }).waitFor();
  await page.screenshot({ path: await screenshotPath('test-results/e2e/settings-model-desktop.png') });
  await page.getByRole('button', { name: 'モデル を閉じる', exact: true }).click();
  await page.getByRole('button', { name: 'モデルを開く', exact: true }).click();
  assert.equal(await model.getByRole('combobox', { name: 'モデル', exact: true }).inputValue(), 'test-model');
  disconnected = true;
  await model.getByRole('button', { name: '接続チェック', exact: true }).click();
  await model.getByRole('textbox', { name: '接続先 URL', exact: true }).waitFor();
  assert.ok((await model.getByRole('alert').innerText()).includes('接続できません'));
  assert.equal((await page.locator('.status-main').innerText()).trim(), '');
  await page.screenshot({ path: await screenshotPath('test-results/e2e/settings-model-error.png') });
  disconnected = false;
  await model.getByRole('textbox', { name: '接続先 URL', exact: true }).fill('http://localhost:11434');
  await model.getByRole('button', { name: '接続チェック', exact: true }).click();
  await page.locator('.model-chip.connected').waitFor();
  await page.getByRole('button', { name: 'モデル を閉じる', exact: true }).click();
  await page.getByRole('button', { name: '変換を開く', exact: true }).click();
  const conversion = page.getByRole('region', { name: '変換設定', exact: true });
  await conversion.getByRole('checkbox', { name: '自動変換', exact: true }).uncheck();
  assert.equal(await conversion.getByRole('checkbox', { name: '入力が止まったら変換', exact: true }).isDisabled(), true);
  await conversion.getByRole('checkbox', { name: '自動変換', exact: true }).check();
  await conversion.getByRole('button', { name: '直接置換', exact: true }).click();
  assert.equal(await conversion.getByRole('button', { name: '直接置換', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: await screenshotPath('test-results/e2e/settings-conversion-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: await screenshotPath('test-results/e2e/settings-conversion-mobile.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: '変換 を閉じる', exact: true }).click();
  await page.getByRole('button', { name: 'モデルを開く', exact: true }).click();
  await page.getByRole('combobox', { name: '表示テーマ' }).selectOption('dark');
  await page.screenshot({ path: await screenshotPath('test-results/e2e/settings-model-mobile-dark.png') });
  await context.close();
  const setupContext = await browser.newContext();
  const setupPage = await setupContext.newPage();
  await setupPage.goto(`${server.resolvedUrls.local[0]}?setup=1`);
  const setup = setupPage.getByRole('dialog', { name: '最初のモデル設定', exact: true });
  await setup.waitFor();
  assert.equal(await setup.getByRole('combobox', { name: 'モデル', exact: true }).isDisabled(), true);
  await setup.getByRole('button', { name: 'あとで設定', exact: true }).click();
  assert.equal(await setupPage.getByRole('dialog').count(), 0);
  console.log('Settings layout E2E passed: shared entry, model selection, error recovery, dependent controls, narrow/dark layout, setup skip.');
} finally { await browser?.close(); await server.close(); }
