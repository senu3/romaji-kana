import { describe, expect, it, vi } from "vitest";
import { preservesProtectedContent } from "./conversionProtection";
import { normalizeInputForPrompt } from "./conversion";
import { convertRomajiToJapaneseDetailed } from "./ollama";
import { defaultSettings } from "./settings";
import { applySpeculativeFallback, convertInputOnce } from "./conversionPipeline";

describe("source protection across conversion routes", () => {
  it.each(["none", "word", "sentence"] as const)("rejects numeric loss in %s mode", async level => {
    const generate = vi.fn().mockResolvedValue({ response: JSON.stringify({ completedKana: "じです。", convertedText: "時です。" }) });
    const result = await convertRomajiToJapaneseDetailed("10zidesu.", { ...defaultSettings, inputCompletionLevel: level }, { models: vi.fn(), generate });
    expect(result.text).toBe("");
    expect(result.suggestionRejected).toBe(true);
    expect(generate).toHaveBeenCalledTimes(1);
  });

  it.each(["none", "word", "sentence"] as const)("accepts intact original digits in %s mode", async level => {
    const generate = vi.fn().mockResolvedValue({ response: JSON.stringify({ completedKana: "10じです。", convertedText: "10時です。" }) });
    const result = await convertRomajiToJapaneseDetailed("10zidesu.", { ...defaultSettings, inputCompletionLevel: level }, { models: vi.fn(), generate });
    expect(result.text).toBe("10時です。");
    expect(result.suggestionRejected).toBeUndefined();
  });

  it("checks the reported final reading independently of the displayed text", async () => {
    const generate = vi.fn().mockResolvedValue({ response: JSON.stringify({ completedKana: "11じです。", convertedText: "11時です。" }) });
    const result = await convertRomajiToJapaneseDetailed("10zidesu.", defaultSettings, { models: vi.fn(), generate });
    expect(result).toMatchObject({ text: "", suggestionRejectedReason: "protected" });
  });

  it("protects original digits through the speculative route", async () => {
    const generate = vi.fn().mockResolvedValueOnce({ response: "10じです。" })
      .mockResolvedValueOnce({ response: JSON.stringify({ completedKana: "11じです。", convertedText: "11時です。" }) });
    const transport = { models: vi.fn(), generate };
    const first = await convertInputOnce("10zidesu.", defaultSettings, transport, {});
    const result = await applySpeculativeFallback("10zidesu.", first, defaultSettings, transport, {});
    expect(result).toMatchObject({ text: "", suggestionRejectedReason: "protected" });
    expect(generate).toHaveBeenCalledTimes(2);
  });

  it("allows a valid protected result on the last typo-completion retry", async () => {
    const invalid = { response: JSON.stringify({ completedKana: "じです。", convertedText: "時です。" }) };
    const generate = vi.fn().mockResolvedValueOnce(invalid).mockResolvedValueOnce(invalid).mockResolvedValueOnce(invalid)
      .mockResolvedValueOnce({ response: JSON.stringify({ completedKana: "10じです。", convertedText: "10時です。" }) });
    const result = await convertRomajiToJapaneseDetailed("10zidesu.", defaultSettings, { models: vi.fn(), generate }, { avoidOutputs: ["10時だ。"] });
    expect(result).toMatchObject({ text: "10時です。", conversionStrategy: "completion" });
    expect(generate).toHaveBeenCalledTimes(4);
  });

  it("retains dictionary and literal terms but rejects extra copies generated by the model", async () => {
    for (const input of ["`OpenAI`nikakunin.", "東京nikakunin."]) {
      const term = input.startsWith("`") ? "OpenAI" : "東京";
      const generate = vi.fn().mockResolvedValue({ response: `${term}に確認。` });
      const result = await convertRomajiToJapaneseDetailed(input, defaultSettings, { models: vi.fn(), generate });
      expect(result).toMatchObject({ text: "", suggestionRejectedReason: "protected" });
    }
    const generate = vi.fn().mockResolvedValue({ response: JSON.stringify({ completedKana: "にかくにん。", convertedText: "に確認。" }) });
    const result = await convertRomajiToJapaneseDetailed("sakura nikakunin.", {
      ...defaultSettings, userDictionary: [{ id: "eval", reading: "sakura", output: "咲良", enabled: true, note: "" }],
    }, { models: vi.fn(), generate });
    expect(result.text).toBe("咲良に確認。");
  });

  it("checks repeated literal terms and their order, including regex metacharacters", () => {
    expect(preservesProtectedContent("咲良と咲良、東京", "咲良、東京", ["咲良", "東京"])).toBe(false);
    expect(preservesProtectedContent("咲良、東京", "東京、咲良", ["咲良", "東京"])).toBe(false);
    expect(preservesProtectedContent("C++とa.b", "C++とa.b", ["C++", "a.b"])).toBe(true);
    expect(preservesProtectedContent("[ほん]", "]ほん[", [])).toBe(false);
    expect(preservesProtectedContent("ほん\nかいぎ", "本 会議", [])).toBe(false);
  });

  it("preserves signs, dates, percentages, numeric order and multiplicity", () => {
    for (const [source, output] of [["-10", "10"], ["10%", "10"], ["2026/10/16", "2026/10/17"], ["10 30", "30 10"], ["10 10", "10"]]) {
      expect(preservesProtectedContent(source, output)).toBe(false);
    }
    expect(preservesProtectedContent("-10 1,500.25 2026/10/16 10%", "-10 1,500.25 2026/10/16 10%")).toBe(true);
  });

  it("does not convert decimal points or numeric grouping separators into Japanese punctuation", () => {
    expect(normalizeInputForPrompt("yosan1,500.25en, kion-3.5do.", defaultSettings)).toBe("yosan1,500.25en、 kion-3.5do。");
  });
});
